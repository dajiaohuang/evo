import { test, expect } from '@playwright/test'

test('tree opens a Wikipedia link and preserves the tree on close', async ({ page }) => {
  const wikiRequests: string[] = []
  page.on('request', request => { if (/^https:\/\/[^/]*wikipedia\.org\//.test(request.url()) || request.url().includes('/wikipedia/abstracts.json')) wikiRequests.push(request.url()) })
  await page.goto('./#/home?view=tree')
  const node = page.locator('svg [data-node-id="pan"]')
  await expect(node).toBeAttached()
  await node.focus()
  await node.dispatchEvent('keydown', { key: 'Enter' })
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('footer a')).toHaveAttribute('href', /wikipedia.org\/wiki\//, { timeout: 20000 })
  await expect(dialog.locator('.wikipedia-window__body')).toContainText(/已找到 Wikipedia 条目|Wikipedia article is available/, { timeout: 20000 })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(node).toBeFocused()
  expect(wikiRequests).toEqual([])
  expect(page.url()).not.toContain('#/taxa')
})

test('the full catalogue tree opens from the static data release', async ({ page }) => {
  const wikiRequests: string[] = []
  page.on('request', request => { if (/^https:\/\/[^/]*wikipedia\.org\//.test(request.url()) || request.url().includes('/wikipedia/abstracts.json')) wikiRequests.push(request.url()) })
  await page.goto('./#/home?view=tree')
  await page.getByRole('button', { name: /打开全量分类树|Open full catalogue tree/ }).click()
  const tree = page.getByRole('tree', { name: /可展开分类树|Expandable catalogue tree/ })
  await expect(tree).toBeVisible({ timeout: 30000 })
  await expect(tree.getByRole('treeitem')).toHaveCount(4)
  await expect(page.getByRole('region', { name: /全量分类树|Full catalogue tree/ })).toContainText('2,429,092')
  await page.getByLabel(/搜索名称|Search names/).fill('Acer crassum')
  await page.locator('.backend-tree__results button').filter({ hasText: '9487' }).click()
  const selected = page.locator('.backend-tree__path a').last()
  await expect(selected).toContainText('Acer crassum')
  await selected.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('.wikipedia-window__body')).toContainText(/已找到 Wikipedia 条目|Wikipedia article is available/)
  await expect(dialog.locator('footer a')).toHaveAttribute('href', /wikipedia\.org\/wiki\//)
  expect(wikiRequests).toEqual([])
})

test('old interactive and static node readers are paused', async ({ page }) => {
  await page.goto('./#/taxa?id=perissodactyla')
  await expect(page.getByRole('heading', { name: /节点页面暂时下线|Node pages are temporarily offline/ })).toBeVisible()
  await page.goto('./taxa/perissodactyla/')
  await expect(page.locator('main')).toContainText(/temporarily offline|暂时下线/)
  await expect(page.locator('.reader-article')).toHaveCount(0)
  await page.goto('./nodes/?id=anything')
  await expect(page.getByRole('heading', { name: '节点页面暂时下线' })).toBeVisible()
  const response = await page.request.get('./nodes/data/0000.json.gz')
  // Vite preview returns its HTML fallback for absent files; Vercel returns 404.
  expect([200, 404]).toContain(response.status())
  const bytes = await response.body()
  expect(bytes.subarray(0, 2).equals(Buffer.from([0x1f, 0x8b]))).toBe(false)
  expect(response.headers()['content-type']).not.toMatch(/gzip|octet-stream/)
})

