import { expect, test } from '@playwright/test'

async function expectNoHorizontalOverflow(page: import('@playwright/test').Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
}

test('desktop home keeps the dashboard focused and places time-matched scenes on the map', async ({ page }) => {
  await page.addInitScript(() => window.localStorage.removeItem('evo-explorer-guide-v2'))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('./#/home?age=66')
  const welcome = page.getByRole('dialog', { name: 'Start with the dashboard or take the quick tour?' })
  await expect(welcome).toHaveCount(0)
  await expect(page.locator('.explorer-stage')).toBeVisible()
  await expect(page.locator('.dashboard-presets')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Reading for this time' })).toBeVisible()
  await expect(page.locator('.explorer-nav')).toHaveCount(0)
  await expect(page.locator('.explorer-inspector')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open detailed tools' }).last().click()
  await expect(page.locator('.explorer-nav')).toBeVisible()
  await expect(page.locator('.explorer-inspector')).toBeVisible()
  await expectNoHorizontalOverflow(page)
})

test('mobile static dossier keeps content and actions inside the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./taxa/perissodactyla/')
  await expect(page.getByRole('heading', { name: 'Perissodactyla', exact: true })).toBeVisible()
  await expect(page.locator('.dek')).not.toBeEmpty()
  await expect(page.locator('.actions .button')).toHaveCount(2)
  await expectNoHorizontalOverflow(page)
})

test('static dossier links preserve a taxonomy ID containing a colon', async ({ page }) => {
  await page.goto('./taxa/txn~3A371114/')
  await expect(page.getByRole('heading', { name: 'Tethydraco', exact: true })).toBeVisible()
  const explorer = new URL(await page.getByRole('link', { name: 'Open in Explorer' }).getAttribute('href') ?? '', page.url())
  expect(new URLSearchParams(explorer.hash.split('?')[1]).get('taxon')).toBe('txn:371114')
  const report = new URL(await page.locator('.actions a').last().getAttribute('href') ?? '')
  expect(report.searchParams.get('body')).toContain('Entity: txn:371114')
})

test('first Explorer visit walks through time, map, tree and evidence once', async ({ page }) => {
  await page.addInitScript(() => window.localStorage.removeItem('evo-explorer-guide-v2'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./#/home?age=66')
  await page.getByRole('button', { name: 'Tutorial' }).click()
  const guide = page.getByRole('complementary', { name: 'Explorer quick guide' })
  await expect(guide).toBeVisible()
  await expect(guide.getByRole('listitem')).toHaveCount(4)
  await expect(guide.getByRole('heading', { name: 'Set a time context' })).toBeVisible()
  await expectNoHorizontalOverflow(page)

  await guide.getByRole('button', { name: 'Next' }).click()
  await expect(guide.getByRole('heading', { name: 'Read the map as a reconstruction' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Map', exact: true })).toHaveClass(/is-active/)
  await guide.getByRole('button', { name: 'Next' }).click()
  await expect(guide.getByRole('heading', { name: 'Switch to the tree without changing context' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tree', exact: true })).toHaveClass(/is-active/)
  await guide.getByRole('button', { name: 'Next' }).click()
  await expect(guide.getByRole('heading', { name: 'Check evidence before drawing a conclusion' })).toBeVisible()
  await expect(page.locator('.explorer-inspector')).toBeVisible()
  await guide.getByRole('button', { name: 'Finish tour' }).click()
  await expect(guide).toBeHidden()
  await expect(page.locator('.explorer-inspector')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('complementary', { name: 'Explorer quick guide' })).toHaveCount(0)
  await expectNoHorizontalOverflow(page)
})

