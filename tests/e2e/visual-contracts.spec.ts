test('map evidence cards follow range and claim links as geological time changes', async ({ page }) => {
  await page.addInitScript(() => window.localStorage.setItem('evo-explorer-guide-v2', 'dismissed'))
  await page.goto('./#/home?age=507')
  const cards = page.getByRole('region', { name: 'Reading for this time' })
  await expect(cards).toBeVisible()
  await cards.getByRole('button', { name: /^Show \d+ more scenes$/ }).click()
  await expect(cards).toContainText('Olenoides serratus')
  await expect(cards.getByRole('link', {name: 'Continue reading →'}).first()).toBeVisible()

  await page.locator('.explorer-timeline input[type="number"]').fill('10')
  await expect(cards).not.toContainText('Olenoides serratus')
  await expect(cards).toContainText('Perissodactyla')
  await expectNoHorizontalOverflow(page)
})
